//! The android backend: `SiteModel` → real, buildable Gradle project
//! (ADR-0021).
//!
//! The generated app renders every page as **native Android views**
//! (`TextView`, `Button`, `ImageView`, plain `Activity`) — no WebView,
//! no AndroidX, no permissions. Navigation happens in place; image
//! sources resolve from the project's `assets/` directory with the alt
//! text as the honest fallback when the file is missing.
//!
//! This generator produces a *project*; the APK is produced by building
//! it with one of the build providers:
//! - local Gradle + Android SDK,
//! - the remote CI workflow (`.github/workflows/android-app.yml`),
//! - or simply handing the exported project to Android Studio.
//! Hosts must report which of these actually ran — never claim an APK
//! from an export.

use crate::site::{Element, PageModel, SiteModel};

/// Files for the exported Android project. `assets` entries are copied
/// verbatim under `app/src/main/assets/` so generated `image` elements
/// can load them (paths like `assets/logo.png` map to `logo.png`).
pub fn generate(site: &SiteModel, assets: &[(String, Vec<u8>)]) -> Vec<crate::backend::OutputFile> {
    assert!(!site.pages.is_empty(), "checker guarantees at least one page");
    let pkg = package_for(&site.name);
    let mut files: Vec<crate::backend::OutputFile> = Vec::new();

    files.push(crate::backend::OutputFile::text("settings.gradle.kts", &settings_gradle(site)));
    files.push(crate::backend::OutputFile::text("build.gradle.kts", ROOT_BUILD_GRADLE));
    files.push(crate::backend::OutputFile::text("gradle.properties", GRADLE_PROPERTIES));
    files.push(crate::backend::OutputFile::text(
        "gradle/wrapper/gradle-wrapper.properties",
        GRADLE_WRAPPER_PROPERTIES,
    ));
    files.push(crate::backend::OutputFile::text("app/build.gradle.kts", &app_build_gradle(&pkg)));
    files.push(crate::backend::OutputFile::text(
        "app/src/main/AndroidManifest.xml",
        &manifest(),
    ));
    files.push(crate::backend::OutputFile::text(
        &format!("app/src/main/java/dev/kinn/site/{}/MainActivity.kt", pkg),
        &main_activity(site, &pkg),
    ));
    files.push(crate::backend::OutputFile::text(
        "app/src/main/res/values/strings.xml",
        &strings_xml(site),
    ));
    files.push(crate::backend::OutputFile::text("app/src/main/res/values/colors.xml", COLORS_XML));
    files.push(crate::backend::OutputFile::text("app/src/main/res/values/themes.xml", THEMES_XML));
    files.push(crate::backend::OutputFile::text("README.md", &readme(site)));

    for (path, data) in assets {
        files.push(crate::backend::OutputFile {
            path: format!("app/src/main/assets/{}", path),
            data: data.clone(),
        });
    }
    files
}

/// `My Website!` → `my_website` (a valid Kotlin package segment;
/// keywords get a suffix so generation never emits invalid Kotlin).
pub fn package_for(site_name: &str) -> String {
    const KOTLIN_KEYWORDS: [&str; 12] =
        ["in", "is", "if", "for", "when", "as", "by", "do", "else", "try", "class", "object"];
    let mut out = String::new();
    let mut last_us = false;
    for c in site_name.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
            last_us = false;
        } else if !last_us && !out.is_empty() {
            out.push('_');
            last_us = true;
        }
    }
    let out = out.trim_matches('_').to_string();
    let out = if out.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(false) {
        format!("site_{}", out)
    } else {
        out
    };
    if out.is_empty() || KOTLIN_KEYWORDS.contains(&out.as_str()) {
        format!("{}_site", out)
    } else {
        out
    }
}

